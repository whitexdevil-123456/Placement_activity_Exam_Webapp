-- Atomic submission: locks attempt, validates answer IDs, upserts answers, grades objective
-- answers/output matches, computes the score, then sets status and submitted_at in one transaction.
create or replace function public.submit_attempt_atomic(
    p_attempt_id uuid,
    p_student_id uuid,
    p_answers jsonb default '[]'::jsonb,
    p_requested_status text default 'submitted'
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    v_attempt public.attempts%rowtype;
    v_final_status text;
    v_score numeric(10,2) := 0;
    v_max_score numeric(10,2) := 0;
begin
    if p_requested_status not in ('submitted', 'expired') then raise exception 'Invalid requested status'; end if;
    if jsonb_typeof(coalesce(p_answers, '[]'::jsonb)) <> 'array' then raise exception 'p_answers must be a JSON array'; end if;

    select * into v_attempt from public.attempts where id = p_attempt_id for update;
    if not found or v_attempt.student_id <> p_student_id then raise exception 'Attempt not found'; end if;

    if v_attempt.status <> 'in_progress' then
        return jsonb_build_object('id', v_attempt.id, 'status', v_attempt.status, 'score', v_attempt.score, 'max_score', v_attempt.max_score, 'submitted_at', v_attempt.submitted_at);
    end if;

    if exists (
        select 1 from jsonb_to_recordset(coalesce(p_answers, '[]'::jsonb)) as x(question_id bigint, answer_text text, code_answer text, output_answer text)
        left join public.attempt_questions aq on aq.attempt_id = p_attempt_id and aq.question_id = x.question_id
        where aq.question_id is null
    ) then raise exception 'Answer includes a question not assigned to this attempt'; end if;

    if exists (
        select x.question_id from jsonb_to_recordset(coalesce(p_answers, '[]'::jsonb)) as x(question_id bigint, answer_text text, code_answer text, output_answer text)
        group by x.question_id having count(*) > 1
    ) then raise exception 'Duplicate question answers were supplied'; end if;

    -- Create rows for unanswered questions, then overwrite rows included in the final payload.
    insert into public.answers (attempt_id, question_id, updated_at)
    select p_attempt_id, aq.question_id, now() from public.attempt_questions aq where aq.attempt_id = p_attempt_id
    on conflict (attempt_id, question_id) do nothing;

    insert into public.answers (attempt_id, question_id, answer_text, code_answer, output_answer, updated_at)
    select p_attempt_id, x.question_id, x.answer_text, x.code_answer, x.output_answer, now()
      from jsonb_to_recordset(coalesce(p_answers, '[]'::jsonb)) as x(question_id bigint, answer_text text, code_answer text, output_answer text)
    on conflict (attempt_id, question_id) do update
       set answer_text = excluded.answer_text, code_answer = excluded.code_answer,
           output_answer = excluded.output_answer, updated_at = now();

    with evaluated as (
        select aq.attempt_id, aq.question_id, aq.marks, q.question_type, q.expected_output,
               case
                 when q.question_type in ('mcq', 'short') then exists (
                    select 1 from regexp_split_to_table(coalesce(q.correct_answer, ''), E'\\|') as expected(value)
                     where lower(regexp_replace(btrim(coalesce(a.answer_text, '')), '[[:space:]]+', ' ', 'g'))
                         = lower(regexp_replace(btrim(expected.value), '[[:space:]]+', ' ', 'g'))
                 )
                 when q.question_type = 'coding' and nullif(btrim(coalesce(q.expected_output, '')), '') is not null then
                    regexp_replace(btrim(coalesce(a.output_answer, '')), '[[:space:]]+', ' ', 'g')
                    = regexp_replace(btrim(coalesce(q.expected_output, '')), '[[:space:]]+', ' ', 'g')
                 else null
               end as is_correct
          from public.attempt_questions aq
          join public.questions q on q.id = aq.question_id
          join public.answers a on a.attempt_id = aq.attempt_id and a.question_id = aq.question_id
         where aq.attempt_id = p_attempt_id
    )
    update public.answers a
       set is_correct = e.is_correct,
           awarded_marks = case
               when e.question_type in ('mcq', 'short') then case when e.is_correct then e.marks else 0 end
               when e.question_type = 'coding' and nullif(btrim(coalesce(e.expected_output, '')), '') is not null then case when e.is_correct then e.marks else 0 end
               else coalesce(a.awarded_marks, 0)
           end,
           updated_at = now()
      from evaluated e
     where a.attempt_id = e.attempt_id and a.question_id = e.question_id;

    select coalesce(sum(a.awarded_marks), 0), coalesce(sum(aq.marks), 0)
      into v_score, v_max_score
      from public.attempt_questions aq
      left join public.answers a on a.attempt_id = aq.attempt_id and a.question_id = aq.question_id
     where aq.attempt_id = p_attempt_id;

    v_final_status := case when p_requested_status = 'expired' or now() >= v_attempt.deadline_at then 'expired' else 'submitted' end;
    update public.attempts set status = v_final_status, submitted_at = now(), score = round(v_score, 2), max_score = round(v_max_score, 2)
     where id = p_attempt_id and status = 'in_progress';

    return jsonb_build_object('id', p_attempt_id, 'status', v_final_status, 'score', round(v_score, 2), 'max_score', round(v_max_score, 2), 'submitted_at', now());
end;
$$;

-- Store an AI recommendation separately from the official grade.
-- A teacher must explicitly save a grade for the attempt score to change.
create or replace function public.save_ai_suggestion_atomic(
    p_attempt_id uuid,
    p_question_id bigint,
    p_suggested_marks numeric,
    p_feedback text,
    p_ai_confidence numeric
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    v_attempt public.attempts%rowtype;
    v_max_for_question numeric(8,2);
begin
    select * into v_attempt from public.attempts where id = p_attempt_id for update;
    if not found then raise exception 'Attempt not found'; end if;
    if v_attempt.status not in ('submitted', 'expired') then raise exception 'Only finalized attempts can receive AI assessment'; end if;
    if p_suggested_marks < 0 then raise exception 'Suggested marks cannot be negative'; end if;
    if p_ai_confidence is not null and (p_ai_confidence < 0 or p_ai_confidence > 1) then raise exception 'AI confidence must be between 0 and 1'; end if;
    select aq.marks into v_max_for_question
      from public.attempt_questions aq join public.questions q on q.id=aq.question_id
     where aq.attempt_id=p_attempt_id and aq.question_id=p_question_id and q.question_type='coding';
    if not found then raise exception 'Coding question is not assigned to this attempt'; end if;
    if p_suggested_marks > v_max_for_question then raise exception 'Suggested marks exceed the question maximum'; end if;

    insert into public.answers (attempt_id, question_id, ai_suggested_marks, ai_feedback, ai_confidence, grading_source, updated_at)
    values (p_attempt_id, p_question_id, p_suggested_marks, p_feedback, p_ai_confidence, 'ai_suggested', now())
    on conflict (attempt_id, question_id) do update
       set ai_suggested_marks = excluded.ai_suggested_marks,
           ai_feedback = excluded.ai_feedback,
           ai_confidence = excluded.ai_confidence,
           grading_source = case when answers.grading_source='manual' then 'manual' else 'ai_suggested' end,
           updated_at = now();

    return jsonb_build_object('ok', true, 'attempt_id', p_attempt_id, 'question_id', p_question_id,
        'ai_suggested_marks', p_suggested_marks, 'max_marks', v_max_for_question,
        'score', v_attempt.score, 'max_score', v_attempt.max_score, 'grading_source', 'ai_suggested');
end;
$$;

-- Atomic official-grade function used when an instructor saves/overrides a grade.
create or replace function public.grade_answer_atomic(
    p_attempt_id uuid,
    p_question_id bigint,
    p_awarded_marks numeric,
    p_feedback text default null,
    p_ai_confidence numeric default null,
    p_grading_source text default 'manual'
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    v_attempt public.attempts%rowtype;
    v_marks numeric(10,2);
    v_max_for_question numeric(8,2);
    v_score numeric(10,2);
    v_max_score numeric(10,2);
begin
    select * into v_attempt from public.attempts where id = p_attempt_id for update;
    if not found then raise exception 'Attempt not found'; end if;
    if v_attempt.status not in ('submitted', 'expired') then raise exception 'Only finalized attempts can be graded'; end if;
    if p_grading_source not in ('manual', 'ai_suggested') then raise exception 'Invalid grading source'; end if;
    if p_awarded_marks < 0 then raise exception 'Awarded marks cannot be negative'; end if;
    select marks into v_max_for_question from public.attempt_questions where attempt_id = p_attempt_id and question_id = p_question_id;
    if not found then raise exception 'Question is not assigned to this attempt'; end if;
    if p_awarded_marks > v_max_for_question then raise exception 'Awarded marks exceed the question maximum'; end if;
    if p_ai_confidence is not null and (p_ai_confidence < 0 or p_ai_confidence > 1) then raise exception 'AI confidence must be between 0 and 1'; end if;

    insert into public.answers (attempt_id, question_id, awarded_marks, is_correct, graded_at, grading_source, ai_feedback, ai_confidence, updated_at)
    values (p_attempt_id, p_question_id, p_awarded_marks, (p_awarded_marks >= v_max_for_question), now(), p_grading_source, p_feedback, p_ai_confidence, now())
    on conflict (attempt_id, question_id) do update
       set awarded_marks = excluded.awarded_marks,
           is_correct = excluded.is_correct,
           graded_at = now(),
           grading_source = excluded.grading_source,
           ai_feedback = case when p_grading_source = 'ai_suggested' then excluded.ai_feedback else answers.ai_feedback end,
           ai_confidence = case when p_grading_source = 'ai_suggested' then excluded.ai_confidence else answers.ai_confidence end,
           updated_at = now();

    select coalesce(sum(coalesce(a.awarded_marks, 0)), 0), coalesce(sum(aq.marks), 0)
      into v_score, v_max_score
      from public.attempt_questions aq
      left join public.answers a on a.attempt_id = aq.attempt_id and a.question_id = aq.question_id
     where aq.attempt_id = p_attempt_id;
    update public.attempts set score = round(v_score, 2), max_score = round(v_max_score, 2) where id = p_attempt_id;
    return jsonb_build_object('ok', true, 'attempt_id', p_attempt_id, 'question_id', p_question_id, 'awarded_marks', p_awarded_marks,
        'score', round(v_score, 2), 'max_score', round(v_max_score, 2), 'grading_source', p_grading_source);
end;
$$;



-- Create a one-time password-reset token atomically. Requests for the same account are
-- rate-limited to one token per 60 seconds and any older live token is invalidated.
create or replace function public.create_student_password_reset(
    p_student_id uuid,
    p_token_hash text
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    v_student_id uuid;
begin
    select s.id into v_student_id
      from public.students s
     where s.id = p_student_id
       and s.is_active = true
       and s.registration_pending = false
     for update;
    if not found then
        return false;
    end if;

    if exists (
        select 1 from public.student_password_reset_tokens t
         where t.student_id = p_student_id
           and t.created_at > now() - interval '60 seconds'
    ) then
        return false;
    end if;

    update public.student_password_reset_tokens
       set used_at = now()
     where student_id = p_student_id and used_at is null;

    delete from public.student_password_reset_tokens
     where created_at < now() - interval '7 days';

    insert into public.student_password_reset_tokens (student_id, token_hash, expires_at)
    values (p_student_id, p_token_hash, now() + interval '30 minutes');

    return true;
end;
$$;

-- Consume a reset token and update the student's password in the same transaction.
create or replace function public.consume_student_password_reset(
    p_token_hash text,
    p_new_password_hash text
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
    v_student_id uuid;
begin
    select t.student_id into v_student_id
      from public.student_password_reset_tokens t
     where t.token_hash = p_token_hash
       and t.used_at is null
       and t.expires_at > now()
     for update;
    if not found then
        return false;
    end if;

    update public.students
       set password_hash = p_new_password_hash
     where id = v_student_id
       and is_active = true
       and registration_pending = false;
    if not found then
        return false;
    end if;

    update public.student_password_reset_tokens
       set used_at = now()
     where token_hash = p_token_hash and used_at is null;

    return true;
end;
$$;

